const daysAgo = (now: number, d: number) => new Date(now - d * DAY).toISOString();

/** The next date that falls on one of `weekdays` (0 = Sunday), at least `minDays` away, at hh:mm. */
function nextOn(now: number, weekdays: number[], time: string, minDays = 0): string {
    const [h, m] = time.split(':').map(Number);
    for (let i = minDays; i < minDays + 14; i++) {
        const d = new Date(now + i * DAY);
        if (weekdays.includes(d.getDay())) {
            d.setHours(h!, m!, 0, 0);
            if (d.getTime() > now) return d.toISOString();
        }
    }
    return new Date(now + 7 * DAY).toISOString();
}

